    public static void modify(ModifyDefaultComponentsEvent event) {
        event.modifyMatching((item, components) -> BURN_TIMES.containsKey(BuiltInRegistries.ITEM.getKey(item).toString()),
            (components, context, item) -> components.set(DataComponents.COOKING_FUEL,
                new CookingFuel(provider(BURN_TIMES.get(BuiltInRegistries.ITEM.getKey(item).toString())),
                    ContextFloatProviders.COOKING_DEFAULT_SPEED_MULTIPLIER)));
    }
    public static ResourceKey<ContextIntProvider> provider(int ticks) {
        return switch(ticks) {
            case 67 -> ContextIntProviders.COOKING_TIME_WOOL_CARPETS;
            case 100 -> ContextIntProviders.COOKING_TIME_WOOD_ITEMS_EXTRA_SMALL;
            case 150 -> ContextIntProviders.COOKING_TIME_WOOD_SLABS;
            case 200 -> ContextIntProviders.COOKING_TIME_WOOD_ITEMS_LARGE;
            case 300 -> ContextIntProviders.COOKING_TIME_WOOD_BLOCKS;
            case 800 -> ContextIntProviders.COOKING_TIME_HANGING_SIGNS;
            case 1200 -> ContextIntProviders.COOKING_TIME_BOATS;

            default -> throw new IllegalArgumentException("Unknown legacy burn time: "+ticks);
        };
    }
